def update_readme(blocks: dict[str, str]) -> None:
    text = README.read_text()
    for name, block in blocks.items():
        start_marker, end_marker = README_BLOCKS[name]
        start = text.index(start_marker) + len(start_marker)
        end = text.index(end_marker)
        text = text[:start] + "\n" + block + "\n" + text[end:]
    README.write_text(text)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--judge", default=JUDGE_MODEL, choices=sorted(MODELS))
    parser.add_argument("--judge-pass", type=int, default=0)
    parser.add_argument("--sample", type=int, default=0)
    args = parser.parse_args()
    key = analysis.GridKey(args.judge, args.judge_pass, args.sample)

    res = analysis.rounded(analysis.run(key=key))
    results, report = RESULTS, REPORT
    if not key.is_default:
        results = RESULTS.with_name(f"metrics.{key.tag}.json")
        report = REPORT.with_name(f"REPORT.{key.tag}.md")
    results.parent.mkdir(parents=True, exist_ok=True)
    results.write_text(json.dumps(res, indent=1, sort_keys=False) + "\n")
    # The encoder students were scored on the committed grid only.
    embedding = json.loads(EMBEDDING.read_text()) if EMBEDDING.exists() and key.is_default else None
    report.write_text(render(res, embedding))
    written = f"{results.relative_to(ROOT)}, {report.relative_to(ROOT)}"
    if key.is_default:
        update_readme(
            {
                "headline": readme_headline(res),
                "results": readme_block(res, embedding),
                "tuned": readme_tuned(res),
            }
        )
        written += " and the generated blocks of README.md"
    print(f"wrote {written}")


if __name__ == "__main__":
    main()
