def num(x: float, digits: int = 2, signed: bool = False) -> str:
    """Fixed decimals, except that a value which would round to zero keeps its sign with one more
    decimal (+0.002, not 0.00), so an interval that just excludes zero does not print as touching it."""
    if abs(x) < 0.5 * 10**-digits:
        if abs(x) < 0.5 * 10 ** -(digits + 1):
            return f"{0:.{digits}f}"
        digits += 1
    return f"{x:+.{digits}f}" if signed else f"{x:.{digits}f}"


def interval(bounds: list[float], digits: int = 2, signed: bool = False) -> str:
    return f"[{num(bounds[0], digits, signed)}, {num(bounds[1], digits, signed)}]"


def pval(p: float) -> str:
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def money(x: float | None) -> str:
    return "not reached" if x is None else f"${x:.4f}"


def routes(r: list[int]) -> str:
    return "/".join(str(v) for v in r)


def table(header: list[str], rows: list[list[str]]) -> list[str]:
    return ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)] + [
        "| " + " | ".join(r) + " |" for r in rows
    ]


def learned(res: dict) -> list[dict]:
    return [p for p in res["policies"] if p["group"] in ("teacher", "student")]


def best_tuned(res: dict) -> tuple[str, dict]:
    """Best eval-tuned operating point of any teacher or student, over both sweep families."""
    names = {p["name"] for p in learned(res)}
    points = [
        (name, point)
        for name, c in res["curves"].items()
        if name in names
        for point in (c["best_interior_gain"], c["best_threshold_gain"])
        if point is not None
    ]
    return max(points, key=lambda item: item[1]["gain"])


def regret_tracks_deep(res: dict) -> float:
    rows = learned(res)
    deep = [p["routes"][2] for p in rows]
    regret = [p["regret"] for p in rows]
    return float(spearmanr(deep, regret)[0])


def encoder_note(embedding: dict | None) -> str:
    if embedding is None:
        return ""
    agree = [r["eval_agreement"] for r in embedding["students"] if "+prior" not in r["name"]]
    return (
        f" Swapping TF-IDF for a pretrained sentence encoder ({embedding['encoder'].split('/')[-1]}) gives "
        f"{min(agree):.0%}-{max(agree):.0%} (section 3)."
    )


def cv_tuned(res: dict) -> dict[str, dict]:
    names = {p["name"] for p in learned(res)}
    return {name: c["cv_tuned_gain"] for name, c in res["curves"].items() if name in names}


def nominal_in_sample(res: dict) -> list[str]:
    """In-sample best points whose (selection-blind) interval excludes zero."""
    names = {p["name"] for p in learned(res)}
    families = (("best_interior_gain", "quantile rule"), ("best_threshold_gain", "two thresholds"))
    return [
        f"`{name}` ({label}, {num(c[key]['gain'], signed=True)} {interval(c[key]['gain_ci'], signed=True)})"
        for name, c in res["curves"].items()
        if name in names
        for key, label in families
        if c[key] is not None and c[key]["gain_ci"][0] > 0
    ]


def nominal_sentence(res: dict) -> str:
    nominal = nominal_in_sample(res)
    if not nominal:
        return "No in-sample point has a 95% interval above zero."
    count = "One in-sample point has" if len(nominal) == 1 else f"{len(nominal)} in-sample points have"
    return (
        f"{count} a 95% interval above zero: {', '.join(nominal)}. That interval does not account for choosing the "
        f"best of {N_CANDIDATES:,} candidate operating points per router, so it is not evidence."
    )


def tuned_sentence(res: dict) -> str:
    tuned_name, tuned = best_tuned(res)
    cv = cv_tuned(res)
    cv_name = max(cv, key=lambda n: cv[n]["gain"])
    above = [n for n, c in cv.items() if c["gain_ci"][0] > 0]
    cv_text = (
        "none has a 95% interval above zero"
        if not above
        else "only " + ", ".join(f"`{n}`" for n in above) + " has a 95% interval above zero"
    )
    return (
        f"The best in-sample operating point of any teacher or student is {num(tuned['gain'], signed=True)} "
        f"{interval(tuned['gain_ci'], signed=True)} (`{tuned_name}`). {nominal_sentence(res)} Choosing the point by 10-fold "
        f"cross-validation on the eval set instead gives {num(min(c['gain'] for c in cv.values()), signed=True)} "
        f"to {num(cv[cv_name]['gain'], signed=True)} (best: `{cv_name}`, "
        f"{interval(cv[cv_name]['gain_ci'], signed=True)}), and {cv_text}."
    )


def mechanism(res: dict) -> dict:
    """The numbers behind 'why the routers lose', shared by REPORT.md and README.md."""
    cm = res["cost_mechanism"]
    deep_cost = {s: v["cost"][2] for s, v in cm["by_slice"].items()}
    teachers = {n: v for n, v in cm["deep_value"].items() if n.startswith("teacher:")}
    variants = cm["teacher_variants"].values()
    no_call = [v["three tiers"]["without_call"] for v in variants]
    qt = [v["quick or thoughtful"]["without_call"] for v in variants]
    td = [v["thoughtful or deep"]["without_call"] for v in variants]
    return {
        "dear_slice": max(deep_cost, key=deep_cost.get),
        "cheap_slice": min(deep_cost, key=deep_cost.get),
        "dear": max(deep_cost.values()),
        "cheap": min(deep_cost.values()),
        "deep_ppd": [v["deep"]["points_per_dollar"] for v in teachers.values()],
        "rest_ppd": [v["rest"]["points_per_dollar"] for v in teachers.values()],
        "no_call": [r["gain"] for r in no_call],
        "no_call_below": all(r["gain_ci"][1] < 0 for r in no_call),
        "qt": [r["gain"] for r in qt],
        "qt_spans_zero": all(r["gain_ci"][0] < 0 < r["gain_ci"][1] for r in qt),
        "td": [r["gain"] for r in td],
        "td_below": all(r["gain_ci"][1] < 0 for r in td),
    }


def span(values: list[float], digits: int = 2, signed: bool = True) -> str:
    return f"{num(min(values), digits, signed)} to {num(max(values), digits, signed)}"


def mechanism_sentence(res: dict) -> str:
    m = mechanism(res)
    ppd = f"{min(m['deep_ppd']):.1f}-{max(m['deep_ppd']):.1f}"
    rest = f"{min(m['rest_ppd']):.1f}-{max(m['rest_ppd']):.1f}"
    return (
        f"Hard questions get long answers, so a deep answer costs ${m['dear']:.4f} on the {m['dear_slice']} slice "
        f"against ${m['cheap']:.4f} on {m['cheap_slice']} ({m['dear'] / m['cheap']:.0f}x). The questions the "
        f"teachers send to deep buy {ppd} judge points per extra dollar over the thoughtful answer, against "
        f"{rest} on the questions they keep off deep. The random split buys deep answers on cheap questions too, "
        "so a router that routes by difficulty loses on this metric even though its choices are informative."
    )


def regularisation_sentence(res: dict) -> str:
    rows = res["regularisation"]
    diffs = [r["minus_teacher"] for r in rows]
    better = [r for r in rows if r["minus_teacher_p"] < 0.05 and r["minus_teacher"] > 0]
    worse = [r for r in rows if r["minus_teacher_p"] < 0.05 and r["minus_teacher"] < 0]
    survivors = sum(p < 0.05 for p in holm([r["minus_teacher_p"] for r in rows]))
    text = (
        f"Refitting the students at every C from {c_range(rows)} and with v0.1's fixed-step trainer "
        f"({len(rows)} refits) moves student-minus-teacher gain from {span(diffs)}."
    )
    if better:
        deep = [r["deep_share"] for r in better]
        text += (
            " Nominally better than their teacher (unadjusted p < 0.05): "
            + ", ".join(f"`{r['student']}` {fit_label(r['c'])}" for r in better)
            + f"; they send {min(deep):.0%}-{max(deep):.0%} of questions to deep."
        )
    if worse:
        text += f" {len(worse)} refits are nominally worse."
    text += (
        " None survives a Holm correction across the refits."
        if survivors == 0
        else f" {survivors} survive a Holm correction across the refits."
    )
    return text


def fit_label(c) -> str:
    return "with the v0.1 trainer" if isinstance(c, str) else f"at C={c:g}"


def c_range(rows: list[dict]) -> str:
    cs = sorted({r["c"] for r in rows if not isinstance(r["c"], str)})
    return f"{cs[0]:g} to {cs[-1]:g}"


def headline(res: dict, embedding: dict | None) -> list[str]:
    by = {p["name"]: p for p in res["policies"]}
    rows = learned(res)
    gains = [p["gain"] for p in rows]
    all_below = all(p["gain_ci"][1] < 0 for p in rows)
    m = mechanism(res)
    fid = res["fidelity"]
    agree = [r["eval_agreement"] for r in fid["students"] if "+prior" not in r["name"]]
    cv_agree = [r["cv_agreement"] for r in fid["students"] if "+prior" not in r["name"]]
    teacher_agree = [v for t, row in fid["teachers"].items() for o, v in row["agreement"].items() if o != t]
    survivors = [c for c in res["comparisons"] if c["p_holm"] < 0.05]
    diag = res["diagnostics"]
    n = res["meta"]["n_eval"]
    q2 = (
        "no teacher-vs-teacher, student-vs-student, student-vs-teacher or distilled-vs-SFT difference survives "
        "the Holm correction"
        if not survivors
        else "only "
        + ", ".join(f"`{c['a']}` - `{c['b']}`" for c in survivors)
        + " survive the Holm correction"
    )
    return [
        f"- **No learned router beats a random split.** Every teacher and student lands {num(-max(gains))} to "
        f"{num(-min(gains))} judge points below the expected score of splitting traffic at random between two "
        f"fixed rungs at the same average cost"
        + (", and every 95% interval is below zero." if all_below else ".")
        + f" The per-question oracle, which needs every answer and its score, is "
        f"{num(by['oracle']['gain'], signed=True)} {interval(by['oracle']['gain_ci'], signed=True)} above it.",
        "- **They lose because of what deep answers cost on hard questions (section 1).** "
        + mechanism_sentence(res)
        + f" Without their own routing call the teachers still score {span(m['no_call'])}"
        + (", every interval below zero" if m["no_call_below"] else "")
        + f". Without the call and restricted to quick or thoughtful they score {span(m['qt'])}"
        + (" (every interval spans zero)" if m["qt_spans_zero"] else "")
        + f"; restricted to thoughtful or deep, {span(m['td'])}"
        + (" (every interval below zero)." if m["td_below"] else "."),
        "- **Tuning the operating point does not rescue them (section 2).** " + tuned_sentence(res),
        f"- **Students imitate their teachers only partly (Q1).** Agreement with their own teacher is "
        f"{min(cv_agree):.0%}-{max(cv_agree):.0%} in cross-validation on the training pool and "
        f"{min(agree):.0%}-{max(agree):.0%} on the eval questions; the teachers agree with each other "
        f"{min(teacher_agree):.0%}-{max(teacher_agree):.0%}." + encoder_note(embedding),
        f"- **The best-teacher question (Q2) gets no answer from this data.** The three teachers label the eval "
        f"set almost identically, and {q2} (section 4). The student-vs-teacher comparisons also depend on how "
        "the students are regularised, and C is chosen for imitation, not routing value. "
        + regularisation_sentence(res),
        f"- **Regret, the v0.1 headline metric, mostly measures how often a router picks deep.** Across teachers "
        f"and students, Spearman rho between questions sent to deep and regret is {regret_tracks_deep(res):.2f}: "
        f"the deep rung ties or beats both cheaper rungs on {diag['deep_ties_or_beats']} of {n} questions.",
    ]


def main_table(res: dict) -> list[str]:
    rows = []
    for p in res["policies"]:
        rows.append(
            [
                f"`{p['name']}`",
                routes(p["routes"]),
                f"{num(p['score'])} {interval(p['score_ci'])}",
                f"${p['cost']:.4f}",
                f"{num(p['gain'], signed=True)} {interval(p['gain_ci'], signed=True)}",
                pval(p["gain_p"]),
                f"{num(p['regret'])} {interval(p['regret_ci'])}",
            ]
        )
    header = [
        "router",
        "routes q/t/d",
        "mean score [95% CI]",
        "$ per question",
        "gain vs random split [95% CI]",
        "p",
        "regret [95% CI]",
    ]
    return table(header, rows)


